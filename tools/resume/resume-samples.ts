import type { ResumeState } from './resume-types'

export interface ResumeSample {
  id: string
  title: string
  category: string
  description: string
  icon: string
  resume: Omit<ResumeState, 'id' | 'createdAt' | 'updatedAt'>
}

function text(content: string) {
  return {
    type: 'doc' as const,
    content: content.split('\n').filter(Boolean).map(line => {
      if (line.startsWith('• ')) {
        return {
          type: 'bulletList' as const,
          content: [{
            type: 'listItem' as const,
            content: [{ type: 'paragraph' as const, content: [{ type: 'text' as const, text: line.slice(2) }] }],
          }],
        }
      }
      return {
        type: 'paragraph' as const,
        content: [{ type: 'text' as const, text: line }],
      }
    }),
  }
}

