import { jsPDF } from 'jspdf'
import type { NoticeData } from './types'
import { NOTICE_TYPES } from './tenancy-data'

// ─── Constants ────────────────────────────────────────────────────────────────

const PAGE_WIDTH = 210
const PAGE_HEIGHT = 297
const MARGIN = 20
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2
const FOOTER_HEIGHT = 15
const BOTTOM_LIMIT = PAGE_HEIGHT - FOOTER_HEIGHT - MARGIN

// ─── Helpers ──────────────────────────────────────────────────────────────────

function addFooter(doc: jsPDF): void {
  const pageCount = doc.getNumberOfPages()
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)
    doc.setFontSize(8)
    doc.setTextColor(120, 120, 120)
    doc.text(
      'Generated by Toolk1t — toolk1t.com | This is not legal advice',
      PAGE_WIDTH / 2,
      PAGE_HEIGHT - 8,
      { align: 'center' },
    )
    doc.setTextColor(0, 0, 0)
  }
}

function checkPageBreak(doc: jsPDF, y: number, needed = 10): number {
  if (y + needed > BOTTOM_LIMIT) {
    doc.addPage()
    return MARGIN + 10
  }
  return y
}

function labelValue(
  doc: jsPDF,
  label: string,
  value: string,
  y: number,
): number {
  y = checkPageBreak(doc, y, 8)
  doc.setFont('helvetica', 'bold')
  doc.text(`${label}:`, MARGIN, y)
  doc.setFont('helvetica', 'normal')
  const labelWidth = doc.getTextWidth(`${label}: `)
  doc.text(value, MARGIN + labelWidth, y)
  return y + 7
}

function formatDate(dateStr: string): string {
  if (!dateStr) return '—'
  const d = new Date(dateStr)
  return d.toLocaleDateString('en-NZ', {
    day: '2-digit',
    month: 'long',
    year: 'numeric',
  })
}

function calculateEffectiveDate(noticeDate: string, days: number): string {
  if (!noticeDate) return '—'
  const effectiveMs = new Date(noticeDate).getTime() + days * 86400000
  const effective = new Date(effectiveMs)
  return effective.toLocaleDateString('en-NZ', {
    day: '2-digit',
    month: 'long',
    year: 'numeric',
  })
}

function formatCurrency(amount: number): string {
  return `$${amount.toFixed(2)}`
}

function buildTitle(type: string): string {
  const typeInfo = NOTICE_TYPES[type]
  if (!typeInfo) return 'NOTICE TO TERMINATE TENANCY'

  switch (type) {
    case '90-day':
      return 'NOTICE TO TERMINATE TENANCY — 90 DAYS'
    case '42-day':
      return 'NOTICE TO TERMINATE TENANCY — 42 DAYS'
    case '14-day-rent':
      return 'NOTICE TO REMEDY — RENT ARREARS (14 DAYS)'
    case '28-day-tenant':
      return 'NOTICE OF TERMINATION BY TENANT — 28 DAYS'
    case '21-day-fixed':
      return 'NOTICE NOT TO EXTEND FIXED-TERM TENANCY — 21 DAYS'
    default:
      return `NOTICE TO TERMINATE TENANCY — ${typeInfo.days} DAYS`
  }
}

// ─── PDF Generator ────────────────────────────────────────────────────────────

export function generateNoticePdf(data: NoticeData): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  let y = MARGIN + 5

  const typeInfo = NOTICE_TYPES[data.type]
  const days = typeInfo?.days ?? 90

  // ── Title block ─────────────────────────────────────────────────────────────
  doc.setFontSize(16)
  doc.setFont('helvetica', 'bold')
  doc.text(buildTitle(data.type), PAGE_WIDTH / 2, y, { align: 'center' })
  y += 10

  doc.setFontSize(11)
  doc.setFont('helvetica', 'normal')
  doc.text(
    'Under the Residential Tenancies Act 1986',
    PAGE_WIDTH / 2,
    y,
    { align: 'center' },
  )
  y += 6

  if (typeInfo) {
    doc.setFontSize(9)
    doc.setTextColor(100, 100, 100)
    doc.text(`${typeInfo.actSection}`, PAGE_WIDTH / 2, y, { align: 'center' })
    doc.setTextColor(0, 0, 0)
    y += 4
  }

  doc.setDrawColor(180, 180, 180)
  doc.line(MARGIN, y, PAGE_WIDTH - MARGIN, y)
  y += 10

  // ── From / To ────────────────────────────────────────────────────────────
  doc.setFontSize(10)
  y = labelValue(doc, 'From', data.fromName || '—', y)
  y = labelValue(doc, 'From Address', data.fromAddress || '—', y)
  y += 4
  y = labelValue(doc, 'To', data.toName || '—', y)
  y = labelValue(doc, 'To Address', data.toAddress || '—', y)
  y += 6

  // ── Property ─────────────────────────────────────────────────────────────
  doc.setDrawColor(220, 220, 220)
  doc.rect(MARGIN, y - 3, CONTENT_WIDTH, 12, 'S')
  doc.setFont('helvetica', 'bold')
  doc.text('Property:', MARGIN + 3, y + 5)
  doc.setFont('helvetica', 'normal')
  const propLabelW = doc.getTextWidth('Property: ')
  doc.text(data.propertyAddress || '—', MARGIN + 3 + propLabelW, y + 5)
  y += 16

  // ── Dates ────────────────────────────────────────────────────────────────
  y = labelValue(doc, 'Notice Date', formatDate(data.noticeDate), y)
  y = labelValue(
    doc,
    'Effective Date',
    calculateEffectiveDate(data.noticeDate, days),
    y,
  )
  y += 6

  doc.setDrawColor(180, 180, 180)
  doc.line(MARGIN, y, PAGE_WIDTH - MARGIN, y)
  y += 8

  // ── Type-specific content ─────────────────────────────────────────────────
  doc.setFontSize(10)

  if (data.type === '42-day' && data.reason) {
    y = checkPageBreak(doc, y, 16)
    doc.setFont('helvetica', 'bold')
    doc.text('Reason for Termination:', MARGIN, y)
    doc.setFont('helvetica', 'normal')
    y += 7
    const reasonLines = doc.splitTextToSize(data.reason, CONTENT_WIDTH - 4)
    reasonLines.forEach((line: string) => {
      y = checkPageBreak(doc, y, 7)
      doc.text(line, MARGIN + 4, y)
      y += 6
    })
    y += 4
  }

  if (data.type === '14-day-rent') {
    if (data.amountOwed !== undefined && data.amountOwed > 0) {
      y = labelValue(
        doc,
        'Amount Owed',
        formatCurrency(data.amountOwed),
        y,
      )
    }
    if (data.arrearsPeriod) {
      y = labelValue(doc, 'Arrears Period', data.arrearsPeriod, y)
    }
    y += 4

    y = checkPageBreak(doc, y, 20)
    doc.setFont('helvetica', 'italic')
    const arrearNote =
      'You have the right to pay all outstanding rent arrears in full before the Tenancy Tribunal ' +
      'hearing. If arrears are paid in full, the application for termination may be withdrawn.'
    const arrearLines = doc.splitTextToSize(arrearNote, CONTENT_WIDTH)
    arrearLines.forEach((line: string) => {
      y = checkPageBreak(doc, y, 7)
      doc.text(line, MARGIN, y)
      y += 6
    })
    doc.setFont('helvetica', 'normal')
    y += 4
  }

  // ── Legal statement ──────────────────────────────────────────────────────
  y = checkPageBreak(doc, y, 30)
  doc.setFillColor(248, 248, 252)
  const legalText = buildLegalStatement(data.type, days, typeInfo?.actSection)
  const legalLines = doc.splitTextToSize(legalText, CONTENT_WIDTH - 8)
  const legalBoxH = legalLines.length * 6 + 8
  doc.rect(MARGIN, y - 3, CONTENT_WIDTH, legalBoxH, 'F')
  doc.setFontSize(9)
  doc.setTextColor(60, 60, 80)
  legalLines.forEach((line: string) => {
    y = checkPageBreak(doc, y, 7)
    doc.text(line, MARGIN + 4, y)
    y += 6
  })
  doc.setTextColor(0, 0, 0)
  doc.setFontSize(10)
  y += 6

  // ── Signature section ────────────────────────────────────────────────────
  y = checkPageBreak(doc, y, 40)
  doc.setDrawColor(180, 180, 180)
  doc.line(MARGIN, y, PAGE_WIDTH - MARGIN, y)
  y += 8

  doc.setFont('helvetica', 'bold')
  doc.text('Signed by:', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  y += 3
  doc.text(`Name: ${data.fromName || '______________________________'}`, MARGIN, y)
  y += 12

  doc.line(MARGIN, y, MARGIN + 80, y)
  doc.text('Signature', MARGIN, y + 5)
  doc.line(MARGIN + 100, y, MARGIN + 160, y)
  doc.text('Date', MARGIN + 100, y + 5)
  y += 14

  // ── Footers ──────────────────────────────────────────────────────────────
  addFooter(doc)

  // ── Download ─────────────────────────────────────────────────────────────
  const today = new Date().toISOString().split('T')[0]
  doc.save(`notice-${data.type}-${today}.pdf`)
}

// ─── Legal Statements ─────────────────────────────────────────────────────────

function buildLegalStatement(
  type: string,
  days: number,
  actSection?: string,
): string {
  const section = actSection ?? 'the Residential Tenancies Act 1986'

  switch (type) {
    case '90-day':
      return (
        `This notice is given under ${section} of the Residential Tenancies Act 1986. ` +
        `The landlord requires the tenant(s) to vacate the property on or before the effective date stated above. ` +
        `The tenancy will terminate ${days} days from the date this notice is served. ` +
        `Tenants who disagree with this notice may apply to the Tenancy Tribunal within the notice period.`
      )
    case '42-day':
      return (
        `This notice is given under ${section} of the Residential Tenancies Act 1986 for the reason stated above. ` +
        `The landlord requires the tenant(s) to vacate the property on or before the effective date stated above. ` +
        `The tenancy will terminate ${days} days from the date this notice is served. ` +
        `Tenants who disagree with this notice may apply to the Tenancy Tribunal within the notice period.`
      )
    case '14-day-rent':
      return (
        `This notice is given under ${section} of the Residential Tenancies Act 1986 due to rent arrears of at least 21 days. ` +
        `If the rent arrears are not remedied within ${days} days of this notice, the landlord may apply to the Tenancy Tribunal ` +
        `for termination of the tenancy. Payment of all arrears in full before the Tribunal hearing will stop the termination process.`
      )
    case '28-day-tenant':
      return (
        `This notice is given under ${section} of the Residential Tenancies Act 1986. ` +
        `The tenant(s) hereby give notice that the tenancy will terminate ${days} days from the date of this notice. ` +
        `The tenant(s) will vacate the property and return keys on or before the effective date stated above.`
      )
    case '21-day-fixed':
      return (
        `This notice is given under ${section} of the Residential Tenancies Act 1986. ` +
        `The tenant(s) hereby give notice that they do not wish to extend or renew the fixed-term tenancy beyond its end date. ` +
        `This notice must be given at least ${days} days before the fixed-term end date. ` +
        `The tenant(s) will vacate the property and return all keys on or before the fixed-term end date.`
      )
    default:
      return (
        `This notice is given under the Residential Tenancies Act 1986. ` +
        `The tenancy will terminate ${days} days from the date this notice is served.`
      )
  }
}
