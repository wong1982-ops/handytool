import { jsPDF } from 'jspdf'
import type { AgreementData } from './types'

// ─── Constants ────────────────────────────────────────────────────────────────

const PAGE_WIDTH = 210
const PAGE_HEIGHT = 297
const MARGIN = 20
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2
const FOOTER_HEIGHT = 15
const BOTTOM_LIMIT = PAGE_HEIGHT - FOOTER_HEIGHT - MARGIN

// ─── Helpers ──────────────────────────────────────────────────────────────────

function addFooter(doc: jsPDF): void {
  const pageCount = doc.getNumberOfPages()
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)
    doc.setFontSize(8)
    doc.setTextColor(120, 120, 120)
    doc.text(
      'Generated by Toolk1t — toolk1t.com | This is not legal advice',
      PAGE_WIDTH / 2,
      PAGE_HEIGHT - 8,
      { align: 'center' },
    )
    doc.setTextColor(0, 0, 0)
  }
}

function checkPageBreak(doc: jsPDF, y: number, needed = 10): number {
  if (y + needed > BOTTOM_LIMIT) {
    doc.addPage()
    return MARGIN + 10
  }
  return y
}

function sectionTitle(doc: jsPDF, title: string, y: number): number {
  y = checkPageBreak(doc, y, 14)
  doc.setFontSize(11)
  doc.setFont('helvetica', 'bold')
  doc.setFillColor(240, 244, 255)
  doc.rect(MARGIN, y - 5, CONTENT_WIDTH, 10, 'F')
  doc.text(title, MARGIN + 2, y + 2)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  return y + 12
}

function labelValue(
  doc: jsPDF,
  label: string,
  value: string,
  y: number,
  indent = 0,
): number {
  y = checkPageBreak(doc, y, 8)
  doc.setFont('helvetica', 'bold')
  doc.text(`${label}:`, MARGIN + indent, y)
  doc.setFont('helvetica', 'normal')
  const labelWidth = doc.getTextWidth(`${label}: `) + indent
  doc.text(value, MARGIN + labelWidth, y)
  return y + 7
}

function formatDate(dateStr: string): string {
  if (!dateStr) return '—'
  const d = new Date(dateStr)
  return d.toLocaleDateString('en-NZ', {
    day: '2-digit',
    month: 'long',
    year: 'numeric',
  })
}

function formatCurrency(amount: number): string {
  return `$${amount.toFixed(2)}`
}

// ─── PDF Generator ────────────────────────────────────────────────────────────

export function generateAgreementPdf(data: AgreementData): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  let y = MARGIN + 5

  // ── Title block ─────────────────────────────────────────────────────────────
  doc.setFontSize(18)
  doc.setFont('helvetica', 'bold')
  doc.text('RESIDENTIAL TENANCY AGREEMENT', PAGE_WIDTH / 2, y, {
    align: 'center',
  })
  y += 10

  doc.setFontSize(12)
  doc.setFont('helvetica', 'normal')
  doc.text(
    'Under the Residential Tenancies Act 1986',
    PAGE_WIDTH / 2,
    y,
    { align: 'center' },
  )
  y += 8

  doc.setDrawColor(180, 180, 180)
  doc.line(MARGIN, y, PAGE_WIDTH - MARGIN, y)
  y += 8

  // ── Section 1: Parties ───────────────────────────────────────────────────
  y = sectionTitle(doc, '1. PARTIES', y)

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.text('Landlord', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  y += 7

  y = labelValue(doc, 'Name', data.landlordName || '—', y, 4)
  y = labelValue(doc, 'Address', data.landlordAddress || '—', y, 4)
  y = labelValue(doc, 'Phone', data.landlordPhone || '—', y, 4)
  y = labelValue(doc, 'Email', data.landlordEmail || '—', y, 4)
  y += 4

  doc.setFont('helvetica', 'bold')
  doc.text('Tenant(s)', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  y += 7

  const tenants =
    data.tenantNames && data.tenantNames.length > 0
      ? data.tenantNames.filter(Boolean)
      : ['—']

  tenants.forEach((name, idx) => {
    y = checkPageBreak(doc, y, 8)
    y = labelValue(doc, `Tenant ${idx + 1}`, name, y, 4)
  })
  y += 4

  // ── Section 2: Property ──────────────────────────────────────────────────
  y = sectionTitle(doc, '2. PROPERTY', y)
  y = labelValue(doc, 'Address', data.propertyAddress || '—', y)
  y = labelValue(doc, 'Type', data.propertyType || '—', y)
  y = labelValue(doc, 'Bedrooms', String(data.bedrooms ?? '—'), y)
  y = labelValue(doc, 'Parking', data.hasParking ? 'Yes' : 'No', y)
  y = labelValue(doc, 'Insured', data.isInsured ? 'Yes' : 'No', y)
  y += 4

  // ── Section 3: Tenancy ───────────────────────────────────────────────────
  y = sectionTitle(doc, '3. TENANCY', y)
  y = labelValue(
    doc,
    'Type',
    data.tenancyType === 'fixed' ? 'Fixed Term' : 'Periodic',
    y,
  )
  y = labelValue(doc, 'Start Date', formatDate(data.startDate), y)
  if (data.tenancyType === 'fixed' && data.endDate) {
    y = labelValue(doc, 'End Date', formatDate(data.endDate), y)
  }
  y = labelValue(doc, 'Weekly Rent', formatCurrency(data.weeklyRent || 0), y)
  y = labelValue(doc, 'Payment Method', data.paymentMethod || '—', y)
  y = labelValue(doc, 'Payment Day', data.paymentDay || '—', y)
  y += 4

  // ── Section 4: Bond ──────────────────────────────────────────────────────
  y = sectionTitle(doc, '4. BOND', y)
  y = labelValue(doc, 'Bond Amount', formatCurrency(data.bondAmount || 0), y)
  if (data.petBond && data.petBond > 0) {
    y = labelValue(doc, 'Pet Bond', formatCurrency(data.petBond), y)
  }
  const totalBond = (data.bondAmount || 0) + (data.petBond || 0)
  y = labelValue(doc, 'Total Bond', formatCurrency(totalBond), y)
  y += 4

  // ── Section 5: Chattels ──────────────────────────────────────────────────
  y = sectionTitle(doc, '5. CHATTELS', y)
  const chattelsText =
    data.chattels && data.chattels.length > 0
      ? data.chattels.join(', ')
      : 'None'
  const chattelsLines = doc.splitTextToSize(chattelsText, CONTENT_WIDTH - 4)
  chattelsLines.forEach((line: string) => {
    y = checkPageBreak(doc, y, 7)
    doc.text(line, MARGIN, y)
    y += 6
  })
  y += 4

  // ── Section 6: Additional Terms ──────────────────────────────────────────
  y = sectionTitle(doc, '6. ADDITIONAL TERMS', y)
  y = labelValue(
    doc,
    'Smoking',
    data.smokingAllowed ? 'Allowed' : 'Not permitted on premises',
    y,
  )
  y = labelValue(doc, 'Maximum Occupants', String(data.maxOccupants || '—'), y)

  if (data.additionalConditions && data.additionalConditions.trim()) {
    y = checkPageBreak(doc, y, 10)
    doc.setFont('helvetica', 'bold')
    doc.text('Additional Conditions:', MARGIN, y)
    doc.setFont('helvetica', 'normal')
    y += 7
    const condLines = doc.splitTextToSize(
      data.additionalConditions,
      CONTENT_WIDTH - 4,
    )
    condLines.forEach((line: string) => {
      y = checkPageBreak(doc, y, 7)
      doc.text(line, MARGIN + 4, y)
      y += 6
    })
  }
  y += 4

  // ── Section 7: Healthy Homes ─────────────────────────────────────────────
  y = sectionTitle(doc, '7. HEALTHY HOMES COMPLIANCE', y)
  const hhText =
    'The landlord confirms that this property complies with the Healthy Homes Standards as required ' +
    'under the Residential Tenancies (Healthy Homes Standards) Regulations 2019. A Healthy Homes ' +
    'compliance statement has been provided to the tenant(s) prior to signing this agreement.'
  const hhLines = doc.splitTextToSize(hhText, CONTENT_WIDTH - 4)
  hhLines.forEach((line: string) => {
    y = checkPageBreak(doc, y, 7)
    doc.text(line, MARGIN, y)
    y += 6
  })
  y += 4

  // ── Section 8: Signatures ────────────────────────────────────────────────
  y = checkPageBreak(doc, y, 60)
  y = sectionTitle(doc, '8. SIGNATURES', y)

  const signatureBlock = (role: string, name: string, startY: number): number => {
    let sy = checkPageBreak(doc, startY, 30)
    doc.setFont('helvetica', 'bold')
    doc.text(role, MARGIN, sy)
    doc.setFont('helvetica', 'normal')
    sy += 3
    doc.text(`Name: ${name}`, MARGIN, sy)
    sy += 10
    doc.line(MARGIN, sy, MARGIN + 80, sy)
    doc.text('Signature', MARGIN, sy + 5)
    doc.line(MARGIN + 100, sy, MARGIN + 160, sy)
    doc.text('Date', MARGIN + 100, sy + 5)
    return sy + 14
  }

  y = signatureBlock('Landlord', data.landlordName || '______________________', y)
  y += 4

  const tenantsForSig =
    data.tenantNames && data.tenantNames.filter(Boolean).length > 0
      ? data.tenantNames.filter(Boolean)
      : ['______________________']

  tenantsForSig.forEach((name, idx) => {
    y = signatureBlock(`Tenant ${idx + 1}`, name, y)
    y += 4
  })

  // ── Add footers to all pages ─────────────────────────────────────────────
  addFooter(doc)

  // ── Download ─────────────────────────────────────────────────────────────
  const today = new Date().toISOString().split('T')[0]
  doc.save(`tenancy-agreement-${today}.pdf`)
}
