import { jsPDF } from 'jspdf'
import type { IncidentData } from './types'

// ─── Constants ────────────────────────────────────────────────────────────────

const PAGE_WIDTH = 210
const PAGE_HEIGHT = 297
const MARGIN = 20
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2
const FOOTER_HEIGHT = 15
const BOTTOM_LIMIT = PAGE_HEIGHT - FOOTER_HEIGHT - MARGIN

// ─── Helpers ──────────────────────────────────────────────────────────────────

function addFooter(doc: jsPDF): void {
  const pageCount = doc.getNumberOfPages()
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)
    doc.setFontSize(8)
    doc.setTextColor(120, 120, 120)
    doc.text(
      `Page ${i} of ${pageCount}  |  Generated by Toolk1t — toolk1t.com  |  Retain this record for a minimum of 5 years`,
      PAGE_WIDTH / 2,
      PAGE_HEIGHT - 8,
      { align: 'center' },
    )
    doc.setTextColor(0, 0, 0)
  }
}

function checkPageBreak(doc: jsPDF, y: number, needed = 10): number {
  if (y + needed > BOTTOM_LIMIT) {
    doc.addPage()
    return MARGIN + 10
  }
  return y
}

function sectionTitle(doc: jsPDF, title: string, y: number): number {
  y = checkPageBreak(doc, y, 14)
  doc.setFontSize(10)
  doc.setFont('helvetica', 'bold')
  doc.setFillColor(240, 244, 255)
  doc.rect(MARGIN, y - 4, CONTENT_WIDTH, 9, 'F')
  doc.text(title, MARGIN + 2, y + 2)
  doc.setFont('helvetica', 'normal')
  return y + 11
}

function fieldRow(doc: jsPDF, label: string, value: string, y: number): number {
  y = checkPageBreak(doc, y, 8)
  doc.setFontSize(9)
  doc.setFont('helvetica', 'bold')
  doc.text(`${label}:`, MARGIN, y)
  doc.setFont('helvetica', 'normal')
  const labelW = doc.getTextWidth(`${label}: `) + 1
  const lines = doc.splitTextToSize(value || '—', CONTENT_WIDTH - labelW)
  doc.text(lines[0] || '—', MARGIN + labelW, y)
  y += 6
  for (let i = 1; i < lines.length; i++) {
    y = checkPageBreak(doc, y, 6)
    doc.text(lines[i], MARGIN + labelW, y)
    y += 6
  }
  return y
}

function textBlock(doc: jsPDF, label: string, value: string, y: number): number {
  y = checkPageBreak(doc, y, 8)
  doc.setFontSize(9)
  doc.setFont('helvetica', 'bold')
  doc.text(`${label}:`, MARGIN, y)
  doc.setFont('helvetica', 'normal')
  y += 6
  if (!value?.trim()) {
    doc.text('—', MARGIN + 4, y)
    return y + 8
  }
  const lines = doc.splitTextToSize(value, CONTENT_WIDTH - 4)
  for (const line of lines) {
    y = checkPageBreak(doc, y, 6)
    doc.text(line, MARGIN + 4, y)
    y += 6
  }
  return y + 2
}

function formatIncidentType(type: string): string {
  const labels: Record<string, string> = {
    'near-miss': 'Near Miss',
    'minor': 'Minor Injury / Illness',
    'serious': 'Serious Injury / Illness',
    'notifiable': 'Notifiable Event',
  }
  return labels[type] || type
}

// ─── PDF Generator ────────────────────────────────────────────────────────────

export function generateIncidentPdf(data: IncidentData): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  let y = MARGIN + 5

  // ── Title block ──────────────────────────────────────────────────────────────
  doc.setFillColor(30, 50, 120)
  doc.rect(0, 0, PAGE_WIDTH, 28, 'F')

  doc.setFontSize(16)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(255, 255, 255)
  doc.text('INCIDENT / NEAR MISS REPORT', PAGE_WIDTH / 2, y + 4, { align: 'center' })
  y += 12

  doc.setFontSize(9)
  doc.setFont('helvetica', 'normal')
  doc.text('Health and Safety at Work Act 2015', PAGE_WIDTH / 2, y + 4, { align: 'center' })
  y += 18

  doc.setTextColor(0, 0, 0)

  // ── Notifiable event warning ─────────────────────────────────────────────────
  if (data.type === 'notifiable') {
    y = checkPageBreak(doc, y, 20)
    doc.setFillColor(255, 235, 235)
    doc.setDrawColor(200, 50, 50)
    doc.rect(MARGIN, y - 2, CONTENT_WIDTH, 18, 'FD')
    doc.setFontSize(10)
    doc.setFont('helvetica', 'bold')
    doc.setTextColor(180, 30, 30)
    doc.text('NOTIFIABLE EVENT — IMMEDIATE ACTION REQUIRED', MARGIN + 4, y + 5)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(9)
    doc.text(
      'You must notify WorkSafe NZ immediately: 0800 030 040. Do not disturb the scene unless to assist an injured person,',
      MARGIN + 4,
      y + 11,
    )
    doc.text('prevent further harm, or comply with a WorkSafe NZ direction.', MARGIN + 4, y + 16)
    doc.setTextColor(0, 0, 0)
    y += 22
  }

  // ── Section 1: Incident Details ──────────────────────────────────────────────
  y = sectionTitle(doc, '1. INCIDENT DETAILS', y)
  y = fieldRow(doc, 'Date', data.date || '—', y)
  y = fieldRow(doc, 'Time', data.time || '—', y)
  y = fieldRow(doc, 'Location', data.location || '—', y)
  y = fieldRow(doc, 'Incident Type', formatIncidentType(data.type), y)
  y += 2

  // ── Section 2: Description ───────────────────────────────────────────────────
  y = sectionTitle(doc, '2. INCIDENT DESCRIPTION', y)
  y = textBlock(doc, 'What happened', data.description, y)

  // ── Section 3: People Involved ────────────────────────────────────────────────
  y = sectionTitle(doc, '3. PEOPLE INVOLVED', y)
  y = textBlock(doc, 'Names and roles of people involved', data.people, y)
  y = textBlock(doc, 'Injuries or health effects sustained', data.injuries, y)

  // ── Section 4: Immediate Actions ─────────────────────────────────────────────
  y = sectionTitle(doc, '4. IMMEDIATE ACTIONS TAKEN', y)
  y = textBlock(doc, 'Immediate actions taken at scene', data.immediateActions, y)

  // ── Section 5: Investigation ──────────────────────────────────────────────────
  y = sectionTitle(doc, '5. INVESTIGATION', y)
  y = textBlock(doc, 'Root cause(s) identified', data.rootCause, y)
  y = textBlock(doc, 'Corrective / preventive actions', data.correctiveActions, y)

  // ── Section 6: Reporting ──────────────────────────────────────────────────────
  y = sectionTitle(doc, '6. REPORTING', y)
  y = fieldRow(doc, 'Reported by', data.reportedBy || '—', y)
  y = fieldRow(
    doc,
    'Date reported',
    new Date().toLocaleDateString('en-NZ', { day: '2-digit', month: 'long', year: 'numeric' }),
    y,
  )

  if (data.type === 'notifiable' || data.type === 'serious') {
    y = fieldRow(doc, 'WorkSafe NZ notified', 'Yes — 0800 030 040', y)
    y = fieldRow(doc, 'WorkSafe NZ reference number', '______________________', y)
  }

  y += 6

  // ── Signature block ───────────────────────────────────────────────────────────
  y = checkPageBreak(doc, y, 45)
  y = sectionTitle(doc, '7. SIGN-OFF', y)

  const signatureBox = (role: string, startY: number): number => {
    let sy = checkPageBreak(doc, startY, 30)
    doc.setFontSize(9)
    doc.setFont('helvetica', 'bold')
    doc.text(role, MARGIN, sy)
    doc.setFont('helvetica', 'normal')
    sy += 3
    doc.text('Name:', MARGIN, sy)
    doc.line(MARGIN + 15, sy, MARGIN + 80, sy)
    sy += 8
    doc.text('Signature:', MARGIN, sy)
    doc.line(MARGIN + 20, sy, MARGIN + 80, sy)
    doc.text('Date:', MARGIN + 90, sy)
    doc.line(MARGIN + 100, sy, MARGIN + 160, sy)
    return sy + 12
  }

  y = signatureBox('Person Completing This Report', y)
  y += 2
  y = signatureBox('Supervisor / Manager', y)
  y += 2
  if (data.type === 'serious' || data.type === 'notifiable') {
    y = signatureBox('Health and Safety Representative (if applicable)', y)
  }

  // ── Disclaimer ────────────────────────────────────────────────────────────────
  y = checkPageBreak(doc, y, 20)
  doc.setFontSize(8)
  doc.setTextColor(100, 100, 100)
  doc.setFillColor(248, 248, 248)
  doc.rect(MARGIN, y, CONTENT_WIDTH, 14, 'F')
  const disclaimer =
    'This report is generated for record-keeping and investigation purposes under the Health and Safety at Work Act 2015 (HSWA). ' +
    'It does not constitute legal advice. For notifiable events, you must notify WorkSafe NZ immediately (0800 030 040). ' +
    'Retain this record for a minimum of 5 years. Seek professional H&S advice if in doubt about your obligations.'
  const disclaimerLines = doc.splitTextToSize(disclaimer, CONTENT_WIDTH - 4)
  let dy = y + 5
  for (const line of disclaimerLines) {
    doc.text(line, MARGIN + 2, dy)
    dy += 4
  }
  doc.setTextColor(0, 0, 0)

  // ── Footers ──────────────────────────────────────────────────────────────────
  addFooter(doc)

  // ── Download ─────────────────────────────────────────────────────────────────
  const dateSlug = (data.date || new Date().toISOString().split('T')[0]).replace(/\//g, '-')
  doc.save(`incident-report-${dateSlug}.pdf`)
}
