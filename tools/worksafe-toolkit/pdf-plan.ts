import { jsPDF } from 'jspdf'
import type { PlanData, IndustryId } from './types'

// ─── Constants ────────────────────────────────────────────────────────────────

const PAGE_WIDTH = 210
const PAGE_HEIGHT = 297
const MARGIN = 20
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2
const FOOTER_HEIGHT = 15
const BOTTOM_LIMIT = PAGE_HEIGHT - FOOTER_HEIGHT - MARGIN

// ─── Helpers ──────────────────────────────────────────────────────────────────

function addFooter(doc: jsPDF): void {
  const pageCount = doc.getNumberOfPages()
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)
    doc.setFontSize(8)
    doc.setTextColor(120, 120, 120)
    doc.text(
      `Page ${i} of ${pageCount}  |  Generated by Toolk1t — toolk1t.com  |  This document is not a substitute for professional H&S advice`,
      PAGE_WIDTH / 2,
      PAGE_HEIGHT - 8,
      { align: 'center' },
    )
    doc.setTextColor(0, 0, 0)
  }
}

function checkPageBreak(doc: jsPDF, y: number, needed = 10): number {
  if (y + needed > BOTTOM_LIMIT) {
    doc.addPage()
    return MARGIN + 10
  }
  return y
}

function sectionTitle(doc: jsPDF, title: string, y: number): number {
  y = checkPageBreak(doc, y, 16)
  doc.setFontSize(11)
  doc.setFont('helvetica', 'bold')
  doc.setFillColor(220, 230, 255)
  doc.rect(MARGIN, y - 5, CONTENT_WIDTH, 11, 'F')
  doc.setTextColor(30, 50, 120)
  doc.text(title, MARGIN + 3, y + 3)
  doc.setTextColor(0, 0, 0)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  return y + 14
}

function bodyText(doc: jsPDF, text: string, y: number, indent = 0): number {
  const lines = doc.splitTextToSize(text, CONTENT_WIDTH - indent)
  for (const line of lines) {
    y = checkPageBreak(doc, y, 7)
    doc.text(line, MARGIN + indent, y)
    y += 6
  }
  return y + 2
}

function bulletPoint(doc: jsPDF, text: string, y: number): number {
  y = checkPageBreak(doc, y, 7)
  doc.text('•', MARGIN + 4, y)
  const lines = doc.splitTextToSize(text, CONTENT_WIDTH - 14)
  for (const line of lines) {
    y = checkPageBreak(doc, y, 7)
    doc.text(line, MARGIN + 10, y)
    y += 6
  }
  return y
}

