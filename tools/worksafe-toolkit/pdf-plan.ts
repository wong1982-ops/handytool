// ─── PDF Generator ────────────────────────────────────────────────────────────

export function generatePlanPdf(data: PlanData, industryName: string): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  let y = MARGIN + 5

  // ── Title block ──────────────────────────────────────────────────────────────
  doc.setFillColor(30, 50, 120)
  doc.rect(0, 0, PAGE_WIDTH, 35, 'F')

  doc.setFontSize(18)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(255, 255, 255)
  doc.text('HEALTH AND SAFETY PLAN', PAGE_WIDTH / 2, y + 5, { align: 'center' })
  y += 12

  doc.setFontSize(11)
  doc.setFont('helvetica', 'normal')
  doc.text('Under the Health and Safety at Work Act 2015', PAGE_WIDTH / 2, y + 5, { align: 'center' })
  y += 20

  doc.setTextColor(0, 0, 0)
  doc.setFontSize(12)
  doc.setFont('helvetica', 'bold')
  doc.text(`Business: ${data.businessName || '—'}`, MARGIN, y)
  y += 8
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  doc.text(`Industry: ${industryName}`, MARGIN, y)
  y += 6
  doc.text(`Date Prepared: ${new Date().toLocaleDateString('en-NZ', { day: '2-digit', month: 'long', year: 'numeric' })}`, MARGIN, y)
  y += 3

  doc.setDrawColor(180, 180, 180)
  doc.line(MARGIN, y, PAGE_WIDTH - MARGIN, y)
  y += 8

  // ── Section 1: Policy Statement ──────────────────────────────────────────────
  y = sectionTitle(doc, '1. HEALTH AND SAFETY POLICY STATEMENT', y)
  y = bodyText(doc, getPolicyStatement(data.industry, data.businessName || 'This business'), y)
  y = bodyText(doc, 'Management is committed to:', y)
  const commitments = [
    'Providing and maintaining a safe and healthy work environment',
    'Identifying, assessing, and controlling workplace hazards',
    'Consulting and engaging with workers on H&S matters',
    'Providing training, supervision, and resources to work safely',
    'Investigating incidents and implementing corrective actions',
    'Continuously improving our H&S performance',
  ]
  for (const c of commitments) {
    y = bulletPoint(doc, c, y)
  }
  y += 4

  // ── Section 2: Responsibilities ──────────────────────────────────────────────
  y = sectionTitle(doc, '2. HEALTH AND SAFETY RESPONSIBILITIES', y)

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  y = checkPageBreak(doc, y, 8)
  doc.text('Business Owner / Senior Management', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  y += 6
  const ownerResp = [
    'Ensure H&S is a priority at all levels of the business',
    'Allocate adequate resources for H&S management',
    'Lead by example and comply with all H&S obligations',
    'Review H&S performance regularly and act on findings',
  ]
  for (const r of ownerResp) {
    y = bulletPoint(doc, r, y)
  }
  y += 4

  y = checkPageBreak(doc, y, 8)
  doc.setFont('helvetica', 'bold')
  doc.text('Managers / Supervisors', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  y += 6
  const mgmtResp = [
    'Ensure workers under their supervision work safely',
    'Conduct regular workplace inspections',
    'Investigate incidents and near misses promptly',
    'Ensure workers are trained and competent before undertaking hazardous tasks',
  ]
  for (const r of mgmtResp) {
    y = bulletPoint(doc, r, y)
  }
  y += 4

  y = checkPageBreak(doc, y, 8)
  doc.setFont('helvetica', 'bold')
  doc.text('Workers', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  y += 6
  const workerResp = [
    'Take reasonable care for their own health and safety',
    'Not put others at risk through their actions or omissions',
    'Follow all safe work procedures and use PPE as required',
    'Report all hazards, near misses, and incidents immediately',
    'Cooperate with management on all H&S matters',
  ]
  for (const r of workerResp) {
    y = bulletPoint(doc, r, y)
  }
  y += 4

  // ── Section 3: Hazard Management ─────────────────────────────────────────────
  y = sectionTitle(doc, '3. HAZARD IDENTIFICATION AND MANAGEMENT', y)
  const hazardLines = getHazardManagementText(data.industry, data.questions)
  for (const line of hazardLines) {
    y = bulletPoint(doc, line, y)
  }
  y += 4

  // ── Section 4: Emergency Procedures ──────────────────────────────────────────
  y = sectionTitle(doc, '4. EMERGENCY PROCEDURES', y)
  const emergencyLines = getEmergencyProcedures(data.industry)
  for (const line of emergencyLines) {
    y = bulletPoint(doc, line, y)
  }
  y += 4

  // ── Section 5: Worker Engagement ──────────────────────────────────────────────
  y = sectionTitle(doc, '5. WORKER ENGAGEMENT AND PARTICIPATION', y)
  const engagementItems = [
    'Workers are actively engaged in identifying and managing health and safety risks.',
    'Workers are consulted before decisions that could affect their health and safety are made.',
    'All workers have the right to raise H&S concerns without fear of adverse consequences.',
    'Workers are encouraged to report hazards, near misses, and incidents.',
  ]
  if (data.questions['regular_meetings']) {
    engagementItems.push('Regular H&S meetings and toolbox talks are held to discuss safety issues and share information.')
  }
  const hsrText = 'A Health and Safety Representative (HSR) has been/will be elected to represent workers on H&S matters. The HSR has the right to attend H&S meetings, investigate incidents, and engage with WorkSafe NZ.'
  engagementItems.push(hsrText)
  for (const item of engagementItems) {
    y = bulletPoint(doc, item, y)
  }
  y += 4

  // ── Section 6: Incident Reporting ────────────────────────────────────────────
  y = sectionTitle(doc, '6. INCIDENT REPORTING AND INVESTIGATION', y)
  const incidentItems = [
    'All incidents, near misses, and hazards must be reported to the supervisor or manager immediately.',
    'Serious injuries, illnesses, or incidents (notifiable events) must be reported to WorkSafe NZ immediately by calling 0800 030 040.',
    'The scene of a notifiable event must not be disturbed unless to assist an injured person, prevent further harm, or comply with a WorkSafe NZ direction.',
    'All incidents are investigated to identify root causes and prevent recurrence.',
    'Corrective actions are assigned, tracked, and verified as completed.',
    'Incident records are retained for a minimum of 5 years.',
  ]
  for (const item of incidentItems) {
    y = bulletPoint(doc, item, y)
  }
  y += 4

  // ── Section 7: Review Schedule ────────────────────────────────────────────────
  y = sectionTitle(doc, '7. REVIEW SCHEDULE', y)
  const reviewItems = [
    'This H&S Plan is reviewed annually as a minimum.',
    'The plan is also reviewed following any significant incident, near miss, or change to the business.',
    'Workers are consulted as part of the review process.',
    'The reviewed and updated plan is communicated to all workers.',
  ]
  for (const item of reviewItems) {
    y = bulletPoint(doc, item, y)
  }

  y += 8
  y = checkPageBreak(doc, y, 40)
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(10)
  doc.text('Plan Approved By:', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  y += 10
  doc.line(MARGIN, y, MARGIN + 80, y)
  doc.text('Signature', MARGIN, y + 5)
  doc.line(MARGIN + 100, y, MARGIN + 160, y)
  doc.text('Date', MARGIN + 100, y + 5)
  y += 14
  doc.text(`Name: ${data.businessName ? '(Business Owner / Manager)' : '______________________'}`, MARGIN, y)

  // ── Footers ──────────────────────────────────────────────────────────────────
  addFooter(doc)

  // ── Download ─────────────────────────────────────────────────────────────────
  const today = new Date().toISOString().split('T')[0]
  const slug = (data.businessName || 'business').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
  doc.save(`hs-plan-${slug}-${today}.pdf`)
}
