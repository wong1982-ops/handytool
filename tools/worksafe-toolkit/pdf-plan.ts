function getPolicyStatement(industry: IndustryId, businessName: string): string {
  const statements: Record<IndustryId, string> = {
    construction: `${businessName} is committed to providing a safe and healthy work environment for all workers, contractors, and visitors on all construction sites. We recognise that construction is a high-risk industry and we take our obligations under the Health and Safety at Work Act 2015 (HSWA) seriously. Every worker has the right to go home safe.`,
    hospitality: `${businessName} is committed to ensuring the health, safety, and wellbeing of all staff, contractors, and customers. We recognise the unique hazards present in the hospitality environment — from kitchen operations to public-facing service — and we are dedicated to managing these risks effectively under the Health and Safety at Work Act 2015.`,
    office: `${businessName} is committed to maintaining a safe, healthy, and supportive workplace for all employees and visitors. We recognise that workplace hazards exist even in office environments, including ergonomic risks, psychological harm, and fire hazards, and we will actively manage these under the Health and Safety at Work Act 2015.`,
    retail: `${businessName} is committed to providing a safe working and shopping environment for all employees, contractors, and customers. We will identify and manage hazards including manual handling risks, public aggression, and slips and trips, in accordance with the Health and Safety at Work Act 2015.`,
    agriculture: `${businessName} is committed to the health and safety of all workers, contractors, and visitors on our agricultural operations. We recognise that agriculture carries significant risks including machinery, chemicals, animals, and outdoor work conditions, and we will manage these systematically under the Health and Safety at Work Act 2015.`,
    manufacturing: `${businessName} is committed to providing a safe manufacturing environment for all workers, contractors, and visitors. We will systematically identify, assess, and control all workplace hazards including machinery, chemicals, noise, and manual handling risks, in full compliance with the Health and Safety at Work Act 2015.`,
  }
  return statements[industry]
}

