// ─── Healthy Homes Statement PDF Generator ───────────────────────────────────

import { jsPDF } from 'jspdf'
import type { StatementData, StandardId } from './types'

// ─── Constants ────────────────────────────────────────────────────────────────

const PAGE_WIDTH = 210
const PAGE_HEIGHT = 297
const MARGIN = 20
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2
const FOOTER_HEIGHT = 15
const BOTTOM_LIMIT = PAGE_HEIGHT - FOOTER_HEIGHT - MARGIN

// ─── Helpers ──────────────────────────────────────────────────────────────────

function addFooter(doc: jsPDF): void {
  const pageCount = doc.getNumberOfPages()
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)
    doc.setFontSize(8)
    doc.setTextColor(120, 120, 120)
    doc.text(
      'Generated by Toolk1t — toolk1t.com | This statement is for guidance only',
      PAGE_WIDTH / 2,
      PAGE_HEIGHT - 8,
      { align: 'center' },
    )
    doc.setTextColor(0, 0, 0)
  }
}

function checkPageBreak(doc: jsPDF, y: number, needed = 10): number {
  if (y + needed > BOTTOM_LIMIT) {
    doc.addPage()
    return MARGIN + 10
  }
  return y
}

function formatDate(dateStr: string): string {
  if (!dateStr) return '—'
  const d = new Date(dateStr)
  return d.toLocaleDateString('en-NZ', {
    day: '2-digit',
    month: 'long',
    year: 'numeric',
  })
}

function sectionTitle(doc: jsPDF, label: string, y: number): number {
  y = checkPageBreak(doc, y, 10)
  doc.setFontSize(10)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(60, 60, 80)
  doc.text(label.toUpperCase(), MARGIN, y)
  doc.setTextColor(0, 0, 0)
  doc.setFont('helvetica', 'normal')
  return y + 6
}

function labelValue(doc: jsPDF, label: string, value: string, y: number): number {
  y = checkPageBreak(doc, y, 7)
  doc.setFontSize(10)
  doc.setFont('helvetica', 'bold')
  doc.text(`${label}:`, MARGIN, y)
  doc.setFont('helvetica', 'normal')
  const labelWidth = doc.getTextWidth(`${label}: `)
  doc.text(value || '—', MARGIN + labelWidth, y)
  return y + 7
}

function divider(doc: jsPDF, y: number): number {
  doc.setDrawColor(200, 200, 200)
  doc.line(MARGIN, y, PAGE_WIDTH - MARGIN, y)
  return y + 6
}

// ─── Declaration Labels & Texts ───────────────────────────────────────────────

const STANDARD_NAMES: Record<StandardId, string> = {
  heating: 'Heating Standard',
  insulation: 'Insulation Standard',
  ventilation: 'Ventilation Standard',
  moisture: 'Moisture Ingress & Drainage Standard',
  draught: 'Draught Stopping Standard',
}

const DECLARATION_TEXTS: Record<StandardId, string> = {
  heating:
    'The property has a fixed heater in the main living area capable of heating to at least 18°C.',
  insulation:
    'Ceiling and underfloor insulation meets or exceeds 2008 Building Code requirements.',
  ventilation:
    'Extractor fans are installed in kitchen and bathroom, venting to outside.',
  moisture:
    'The property has effective drainage, guttering, and downpipes with no moisture issues.',
  draught:
    'All unused chimneys/fireplaces are blocked and gaps/holes are sealed.',
}

const STANDARD_ORDER: StandardId[] = [
  'heating',
  'insulation',
  'ventilation',
  'moisture',
  'draught',
]

// ─── PDF Generator ────────────────────────────────────────────────────────────

export function generateStatementPdf(data: StatementData): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  let y = MARGIN + 5

  // ── Title ──────────────────────────────────────────────────────────────────
  doc.setFontSize(16)
  doc.setFont('helvetica', 'bold')
  doc.text(
    'HEALTHY HOMES STANDARDS — COMPLIANCE STATEMENT',
    PAGE_WIDTH / 2,
    y,
    { align: 'center' },
  )
  y += 9

  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(80, 80, 80)
  doc.text(
    'Residential Tenancies (Healthy Homes Standards) Regulations 2019',
    PAGE_WIDTH / 2,
    y,
    { align: 'center' },
  )
  doc.setTextColor(0, 0, 0)
  y += 8

  y = divider(doc, y)

  // ── Property ───────────────────────────────────────────────────────────────
  y = sectionTitle(doc, 'Property', y)
  y = labelValue(doc, 'Address', data.property.address, y)
  y += 4

  // ── Landlord ───────────────────────────────────────────────────────────────
  y = sectionTitle(doc, 'Landlord', y)
  y = labelValue(doc, 'Name', data.landlord.name, y)
  y += 4

  // ── Tenants ────────────────────────────────────────────────────────────────
  y = sectionTitle(doc, 'Tenants', y)
  const tenantList = data.tenants.names.join(', ') || '—'
  y = labelValue(doc, 'Name(s)', tenantList, y)
  y += 4

  // ── Tenancy Start Date ─────────────────────────────────────────────────────
  y = sectionTitle(doc, 'Tenancy', y)
  y = labelValue(doc, 'Start Date', formatDate(data.tenancyStartDate), y)
  y += 4

  y = divider(doc, y)

  // ── Declarations ───────────────────────────────────────────────────────────
  y = checkPageBreak(doc, y, 12)
  doc.setFontSize(11)
  doc.setFont('helvetica', 'bold')
  doc.text('COMPLIANCE DECLARATIONS', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  y += 4

  doc.setFontSize(9)
  doc.setTextColor(80, 80, 80)
  const intro =
    'The landlord declares that, to the best of their knowledge, the property meets the following ' +
    'Healthy Homes Standards as at the tenancy start date.'
  const introLines = doc.splitTextToSize(intro, CONTENT_WIDTH)
  introLines.forEach((line: string) => {
    y = checkPageBreak(doc, y, 6)
    doc.text(line, MARGIN, y)
    y += 5
  })
  doc.setTextColor(0, 0, 0)
  y += 4

  for (const standardId of STANDARD_ORDER) {
    y = checkPageBreak(doc, y, 18)
    const checked = data.declarations[standardId]
    const checkbox = checked ? '☑' : '☐'
    const standardName = STANDARD_NAMES[standardId]
    const declarationText = DECLARATION_TEXTS[standardId]

    doc.setFontSize(10)
    doc.setFont('helvetica', 'bold')
    doc.text(`${checkbox}  ${standardName}`, MARGIN, y)
    y += 6

    doc.setFont('helvetica', 'normal')
    doc.setFontSize(9)
    doc.setTextColor(50, 50, 50)
    const declLines = doc.splitTextToSize(declarationText, CONTENT_WIDTH - 8)
    declLines.forEach((line: string) => {
      y = checkPageBreak(doc, y, 6)
      doc.text(line, MARGIN + 6, y)
      y += 5
    })
    doc.setTextColor(0, 0, 0)
    y += 5
  }

  y = divider(doc, y)

  // ── Signature ──────────────────────────────────────────────────────────────
  y = checkPageBreak(doc, y, 40)
  doc.setFontSize(10)
  doc.setFont('helvetica', 'bold')
  doc.text('Landlord Signature', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  y += 4

  doc.text(`Name: ${data.landlord.name || '______________________________'}`, MARGIN, y)
  y += 12

  doc.setDrawColor(0, 0, 0)
  doc.line(MARGIN, y, MARGIN + 80, y)
  doc.setFontSize(9)
  doc.setTextColor(80, 80, 80)
  doc.text('Signature', MARGIN, y + 5)

  doc.line(MARGIN + 100, y, MARGIN + 160, y)
  doc.text('Date', MARGIN + 100, y + 5)
  doc.setTextColor(0, 0, 0)
  y += 14

  // ── Footer ─────────────────────────────────────────────────────────────────
  addFooter(doc)

  // ── Download ───────────────────────────────────────────────────────────────
  const today = new Date().toISOString().split('T')[0]
  doc.save(`healthy-homes-statement-${today}.pdf`)
}
