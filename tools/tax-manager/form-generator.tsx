'use client'

import { jsPDF } from 'jspdf'
import { TAX_CATEGORIES, COMPANY_TAX_RATE } from './types'
import type { GstSummary, IncomeTaxSummary, TaxEntity } from './types'

// ─── Helpers ────────────────────────────────────────────────────────

function fmt(n: number): string {
  return n.toLocaleString('en-NZ', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
}

function getCategoryLabel(id: string): string {
  return TAX_CATEGORIES.find((c) => c.id === id)?.label ?? id
}

function downloadPdf(doc: jsPDF, filename: string) {
  const blob = doc.output('blob')
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  a.click()
  URL.revokeObjectURL(url)
}

// ─── Shared layout helpers ──────────────────────────────────────────

const PAGE_W = 210
const MARGIN = 20
const CONTENT_W = PAGE_W - MARGIN * 2
const FONT_NORMAL = 10
const FONT_SMALL = 8
const FONT_HEADING = 14
const LINE_HEIGHT = 6

function addHeader(doc: jsPDF, title: string, subtitle: string) {
  doc.setFontSize(FONT_HEADING)
  doc.setFont('helvetica', 'bold')
  doc.text(title, MARGIN, 25)

  doc.setFontSize(FONT_SMALL)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(200, 0, 0)
  doc.text('PRE-FILLED — REVIEW BEFORE FILING', MARGIN, 32)
  doc.setTextColor(0, 0, 0)

  if (subtitle) {
    doc.setFontSize(FONT_SMALL)
    doc.text(subtitle, MARGIN, 38)
  }
}

function addEntityDetails(doc: jsPDF, entity: TaxEntity, period: string, y: number): number {
  doc.setFontSize(FONT_SMALL)
  doc.setFont('helvetica', 'bold')
  doc.text('Entity:', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  doc.text(entity.name, MARGIN + 30, y)
  y += LINE_HEIGHT

  doc.setFont('helvetica', 'bold')
  doc.text('IRD Number:', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  doc.text(entity.ird_number ?? '[NOT PROVIDED]', MARGIN + 30, y)
  y += LINE_HEIGHT

  doc.setFont('helvetica', 'bold')
  doc.text('Period:', MARGIN, y)
  doc.setFont('helvetica', 'normal')
  doc.text(period, MARGIN + 30, y)
  y += LINE_HEIGHT * 1.5

  return y
}

function addBoxRow(doc: jsPDF, label: string, boxLabel: string, value: string, y: number): number {
  doc.setFontSize(FONT_SMALL)
  doc.setFont('helvetica', 'bold')
  doc.text(boxLabel, MARGIN, y)
  doc.setFont('helvetica', 'normal')
  doc.text(label, MARGIN + 15, y)
  doc.text(value, MARGIN + CONTENT_W, y, { align: 'right' })
  y += LINE_HEIGHT
  return y
}

function addFooter(doc: jsPDF) {
  const pageHeight = doc.internal.pageSize.getHeight()
  doc.setFontSize(7)
  doc.setTextColor(120, 120, 120)
  doc.text(
    'Generated by Toolk1t Tax Manager. Not professional tax advice. Review all figures before filing with IRD.',
    MARGIN,
    pageHeight - 10,
  )
  doc.setTextColor(0, 0, 0)
}

// ─── GST101A ────────────────────────────────────────────────────────

export function generateGst101A(summary: GstSummary, entity: TaxEntity, periodLabel: string) {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })

  addHeader(doc, 'GST RETURN — GST101A', `Filing basis: ${entity.gst_basis}`)

  let y = addEntityDetails(doc, entity, periodLabel, 45)

  // Divider
  doc.setDrawColor(200, 200, 200)
  doc.line(MARGIN, y, MARGIN + CONTENT_W, y)
  y += LINE_HEIGHT

  // Box rows
  y = addBoxRow(doc, 'Total sales including GST', 'Box 5', `$${fmt(summary.totalSalesIncGst)}`, y)
  y = addBoxRow(doc, 'Zero-rated supplies', 'Box 6', '$0.00', y)
  y = addBoxRow(doc, 'Total GST collected on sales', 'Box 7', `$${fmt(summary.gstOnSales)}`, y)
  y = addBoxRow(doc, 'Adjustments (from Box 8 worksheet)', 'Box 8', '$0.00', y)

  y += LINE_HEIGHT * 0.5
  doc.line(MARGIN, y, MARGIN + CONTENT_W, y)
  y += LINE_HEIGHT

  y = addBoxRow(doc, 'Total purchases including GST', 'Box 9', `$${fmt(summary.totalPurchasesIncGst)}`, y)
  y = addBoxRow(doc, 'Total GST on purchases', 'Box 11', `$${fmt(summary.gstOnPurchases)}`, y)

  if (summary.entertainmentAdj > 0) {
    y = addBoxRow(doc, 'Entertainment adjustment (50%)', '', `$${fmt(summary.entertainmentAdj)}`, y)
  }

  y += LINE_HEIGHT * 0.5
  doc.line(MARGIN, y, MARGIN + CONTENT_W, y)
  y += LINE_HEIGHT

  doc.setFontSize(FONT_NORMAL)
  doc.setFont('helvetica', 'bold')
  const payLabel = summary.gstToPay >= 0 ? 'GST to pay' : 'GST refund due'
  doc.text('Box 12', MARGIN, y)
  doc.text(payLabel, MARGIN + 15, y)
  doc.text(`$${fmt(Math.abs(summary.gstToPay))}`, MARGIN + CONTENT_W, y, { align: 'right' })

  addFooter(doc)

  downloadPdf(doc, `GST101A_${entity.name.replace(/\s+/g, '_')}_${periodLabel.replace(/\s+/g, '_')}.pdf`)
}

// ─── IR3 (Individual) ───────────────────────────────────────────────

export function generateIR3(summary: IncomeTaxSummary, entity: TaxEntity, taxYear: string) {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })

  addHeader(doc, 'INDIVIDUAL INCOME TAX RETURN — IR3', '')

  let y = addEntityDetails(doc, entity, `Tax year: ${taxYear}`, 45)

  // Business income
  doc.setFontSize(FONT_NORMAL)
  doc.setFont('helvetica', 'bold')
  doc.text('Business Income', MARGIN, y)
  y += LINE_HEIGHT

  doc.setFontSize(FONT_SMALL)
  doc.setFont('helvetica', 'normal')
  doc.text('Total business income', MARGIN + 5, y)
  doc.text(`$${fmt(summary.totalIncome)}`, MARGIN + CONTENT_W, y, { align: 'right' })
  y += LINE_HEIGHT

  doc.text('Other income', MARGIN + 5, y)
  doc.text('[ENTER MANUALLY]', MARGIN + CONTENT_W, y, { align: 'right' })
  y += LINE_HEIGHT * 1.5

  // Expenses schedule
  doc.setFontSize(FONT_NORMAL)
  doc.setFont('helvetica', 'bold')
  doc.text('Expense Schedule', MARGIN, y)
  y += LINE_HEIGHT

  doc.setFontSize(FONT_SMALL)
  doc.setFont('helvetica', 'normal')
  for (const [cat, amount] of Object.entries(summary.expensesByCategory)) {
    doc.text(getCategoryLabel(cat), MARGIN + 5, y)
    doc.text(`$${fmt(amount)}`, MARGIN + CONTENT_W, y, { align: 'right' })
    y += LINE_HEIGHT

    if (y > 260) {
      addFooter(doc)
      doc.addPage()
      y = 25
    }
  }

  doc.setFont('helvetica', 'bold')
  doc.text('Total deductible expenses', MARGIN + 5, y)
  doc.text(`$${fmt(summary.totalExpenses)}`, MARGIN + CONTENT_W, y, { align: 'right' })
  y += LINE_HEIGHT * 1.5

  // Net profit
  doc.line(MARGIN, y, MARGIN + CONTENT_W, y)
  y += LINE_HEIGHT

  doc.setFontSize(FONT_NORMAL)
  doc.text('Net Profit / (Loss)', MARGIN, y)
  doc.text(`$${fmt(summary.netProfit)}`, MARGIN + CONTENT_W, y, { align: 'right' })
  y += LINE_HEIGHT * 1.5

  // Tax estimate
  doc.text('Estimated Income Tax', MARGIN, y)
  doc.text(`$${fmt(summary.estimatedTax)}`, MARGIN + CONTENT_W, y, { align: 'right' })
  y += LINE_HEIGHT

  doc.setFontSize(FONT_SMALL)
  doc.setFont('helvetica', 'normal')
  doc.text(`Effective rate: ${(summary.effectiveRate * 100).toFixed(1)}%`, MARGIN + 5, y)
  y += LINE_HEIGHT * 1.5

  // Manual fields
  doc.setFont('helvetica', 'bold')
  doc.text('Prior year losses', MARGIN + 5, y)
  doc.setFont('helvetica', 'normal')
  doc.text('[ENTER MANUALLY]', MARGIN + CONTENT_W, y, { align: 'right' })
  y += LINE_HEIGHT

  doc.setFont('helvetica', 'bold')
  doc.text('RWT credits', MARGIN + 5, y)
  doc.setFont('helvetica', 'normal')
  doc.text('[ENTER MANUALLY]', MARGIN + CONTENT_W, y, { align: 'right' })
  y += LINE_HEIGHT

  doc.setFont('helvetica', 'bold')
  doc.text('Provisional tax paid', MARGIN + 5, y)
  doc.setFont('helvetica', 'normal')
  doc.text('[ENTER MANUALLY]', MARGIN + CONTENT_W, y, { align: 'right' })
  y += LINE_HEIGHT

  addFooter(doc)

  downloadPdf(doc, `IR3_${entity.name.replace(/\s+/g, '_')}_${taxYear}.pdf`)
}

