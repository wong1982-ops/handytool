import { jsPDF } from 'jspdf'
import type { RiskAssessmentResult } from './types'
import { PROGRAMME_SECTIONS } from './aml-data'

// ─── Constants ───────────────────────────────────────────────────────────────

const PAGE_WIDTH = 210
const PAGE_HEIGHT = 297
const MARGIN = 20
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2
const FOOTER_HEIGHT = 15
const BOTTOM_LIMIT = PAGE_HEIGHT - FOOTER_HEIGHT - MARGIN

// ─── Helpers ─────────────────────────────────────────────────────────────────

function addFooter(doc: jsPDF): void {
  const pageCount = doc.getNumberOfPages()
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i)
    doc.setFontSize(8)
    doc.setTextColor(120, 120, 120)
    doc.text(
      `Page ${i} of ${pageCount}  |  Generated by Toolk1t — toolk1t.com  |  This document is general guidance only — not legal advice`,
      PAGE_WIDTH / 2,
      PAGE_HEIGHT - 8,
      { align: 'center' },
    )
    doc.setTextColor(0, 0, 0)
  }
}

function checkPageBreak(doc: jsPDF, y: number, needed = 10): number {
  if (y + needed > BOTTOM_LIMIT) {
    doc.addPage()
    return MARGIN + 10
  }
  return y
}

function sectionTitle(doc: jsPDF, title: string, y: number): number {
  y = checkPageBreak(doc, y, 16)
  doc.setFontSize(14)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(30, 30, 80)
  doc.text(title, MARGIN, y)
  y += 3
  doc.setDrawColor(61, 106, 242)
  doc.setLineWidth(0.5)
  doc.line(MARGIN, y, MARGIN + CONTENT_WIDTH, y)
  y += 8
  doc.setTextColor(0, 0, 0)
  return y
}

function bodyText(doc: jsPDF, text: string, y: number): number {
  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  const lines = doc.splitTextToSize(text, CONTENT_WIDTH)
  for (const line of lines) {
    y = checkPageBreak(doc, y)
    doc.text(line, MARGIN, y)
    y += 5
  }
  y += 3
  return y
}

function riskBadge(doc: jsPDF, level: string, x: number, y: number): void {
  const colors: Record<string, [number, number, number]> = {
    low: [34, 197, 94],
    medium: [245, 158, 11],
    high: [239, 68, 68],
  }
  const color = colors[level] || [120, 120, 120]
  doc.setFillColor(...color)
  doc.roundedRect(x, y - 4, 24, 7, 2, 2, 'F')
  doc.setFontSize(8)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(255, 255, 255)
  doc.text(level.toUpperCase(), x + 12, y, { align: 'center' })
  doc.setTextColor(0, 0, 0)
}

// ─── Generate PDF ────────────────────────────────────────────────────────────

export function generateCompliancePDF(
  businessName: string,
  riskResult: RiskAssessmentResult | null,
): jsPDF {
  const doc = new jsPDF('p', 'mm', 'a4')
  let y = MARGIN

  // ── Title Page ──────────────────────────────────────────────────────────
  y += 30
  doc.setFontSize(28)
  doc.setFont('helvetica', 'bold')
  doc.setTextColor(30, 30, 80)
  doc.text('AML/CFT', PAGE_WIDTH / 2, y, { align: 'center' })
  y += 12
  doc.text('Compliance Programme', PAGE_WIDTH / 2, y, { align: 'center' })
  y += 20

  doc.setFontSize(16)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(61, 106, 242)
  doc.text(businessName || '[Business Name]', PAGE_WIDTH / 2, y, { align: 'center' })
  y += 10

  doc.setFontSize(11)
  doc.setTextColor(100, 100, 100)
  doc.text(`Prepared: ${new Date().toLocaleDateString('en-NZ', { day: 'numeric', month: 'long', year: 'numeric' })}`, PAGE_WIDTH / 2, y, { align: 'center' })
  y += 6
  doc.text('Prepared under the Anti-Money Laundering and Countering', PAGE_WIDTH / 2, y, { align: 'center' })
  y += 5
  doc.text('Financing of Terrorism Act 2009', PAGE_WIDTH / 2, y, { align: 'center' })

  // ── Divider line ─────────────────────────────────────────────────────────
  y += 15
  doc.setDrawColor(61, 106, 242)
  doc.setLineWidth(0.8)
  doc.line(MARGIN + 30, y, PAGE_WIDTH - MARGIN - 30, y)

  // ── Risk level badge if available ────────────────────────────────────────
  if (riskResult) {
    y += 15
    doc.setFontSize(12)
    doc.setFont('helvetica', 'bold')
    doc.setTextColor(60, 60, 60)
    doc.text('Overall Risk Rating:', PAGE_WIDTH / 2 - 20, y, { align: 'right' })
    riskBadge(doc, riskResult.overallLevel, PAGE_WIDTH / 2 - 15, y)
  }

  // ── Programme Sections ──────────────────────────────────────────────────
  doc.addPage()
  y = MARGIN + 10

  for (const section of PROGRAMME_SECTIONS) {
    y = sectionTitle(doc, section.title, y)

    // If this is the risk assessment section and we have results, add them
    if (section.id === 'risk-assessment' && riskResult) {
      for (const content of section.content) {
        y = bodyText(doc, content, y)
      }

      y = checkPageBreak(doc, y, 30)
      doc.setFontSize(11)
      doc.setFont('helvetica', 'bold')
      doc.text('Risk Assessment Results:', MARGIN, y)
      y += 8

      for (const area of riskResult.areas) {
        y = checkPageBreak(doc, y, 15)
        doc.setFontSize(10)
        doc.setFont('helvetica', 'bold')
        doc.text(`${area.area}:`, MARGIN + 5, y)
        riskBadge(doc, area.level, MARGIN + 80, y)
        y += 8

        for (const rec of area.recommendations) {
          y = checkPageBreak(doc, y)
          doc.setFontSize(9)
          doc.setFont('helvetica', 'normal')
          doc.text(`• ${rec}`, MARGIN + 10, y)
          y += 5
        }
        y += 3
      }
    } else {
      for (const content of section.content) {
        y = bodyText(doc, content, y)
      }
    }

    y += 5
  }

  // ── Signature Section ────────────────────────────────────────────────────
  y = checkPageBreak(doc, y, 60)
  y = sectionTitle(doc, 'Sign-Off', y)

  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.text('This compliance programme has been approved by:', MARGIN, y)
  y += 20

  doc.setDrawColor(0, 0, 0)
  doc.setLineWidth(0.3)

  // Signature line
  doc.line(MARGIN, y, MARGIN + 70, y)
  y += 5
  doc.setFontSize(9)
  doc.text('AML/CFT Compliance Officer — Signature', MARGIN, y)
  y += 15

  doc.line(MARGIN, y, MARGIN + 70, y)
  y += 5
  doc.text('Name (Print)', MARGIN, y)
  y += 15

  doc.line(MARGIN, y, MARGIN + 50, y)
  y += 5
  doc.text('Date', MARGIN, y)

  // ── Disclaimer ────────────────────────────────────────────────────────────
  y += 20
  y = checkPageBreak(doc, y, 25)
  doc.setFillColor(245, 245, 250)
  doc.roundedRect(MARGIN, y - 5, CONTENT_WIDTH, 22, 3, 3, 'F')
  doc.setFontSize(8)
  doc.setFont('helvetica', 'italic')
  doc.setTextColor(100, 100, 100)
  const disclaimer = 'Disclaimer: This document provides general guidance only. It is not legal advice and does not replace the requirement for independent AML/CFT compliance advice. Contact the DIA AML/CFT team for specific guidance. Every reporting entity must tailor their compliance programme to their specific circumstances.'
  const disclaimerLines = doc.splitTextToSize(disclaimer, CONTENT_WIDTH - 10)
  for (const line of disclaimerLines) {
    doc.text(line, MARGIN + 5, y + 2)
    y += 4
  }

  // ── Footers ────────────────────────────────────────────────────────────
  addFooter(doc)

  return doc
}
